
"""Compile the selected SVG path subset to native Buddy drawing calls."""
import re
from pathlib import Path
from xml.etree import ElementTree as ET

root = Path(__file__).resolve().parents[1]
assets = root / "assets" / "pet-final"
token_pattern = re.compile(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)")
counts = {"M": 2, "L": 2, "H": 1, "V": 1, "Q": 4, "Z": 0}

def geometry(data, dx, dy):
    tokens = iter(token_pattern.findall(data))
    token = next(tokens, None)
    command = None
    x = y = start_x = start_y = 0
    result = []
    while token is not None:
        if token.isalpha():
            command = token
            token = next(tokens, None)
        kind = command.upper()
        if kind == "Z":
            result.append("Close")
            x, y = start_x, start_y
            command = None
            continue
        count = counts[kind]
        values = [float(token)] + [float(next(tokens)) for _ in range(count - 1)]
        token = next(tokens, None)
        if kind == "H":
            values = [values[0] + (x if command.islower() else 0), y]
        elif kind == "V":
            values = [x, values[0] + (y if command.islower() else 0)]
        elif command.islower():
            values = [value + (x, y)[i % 2] for i, value in enumerate(values)]
        if kind == "Q":
            qx, qy, ex, ey = values
            values = [x + (qx-x)*2/3, y + (qy-y)*2/3, ex + (qx-ex)*2/3, ey + (qy-ey)*2/3, ex, ey]
        x, y = values[-2:]
        if kind == "M":
            start_x, start_y = x, y
            command = "l" if command.islower() else "L"
        name = {"M": "Move", "L": "Line", "H": "Line", "V": "Line", "Q": "Curve"}[kind]
        args = ", ".join(str(round((value + (dx, dy)[i % 2]) * 10)) for i, value in enumerate(values))
        result.append(f"{name}({args})")
    return ", ".join(result)

def color(value):
    if value == "none":
        return "None"
    if not re.fullmatch(r"#[a-fA-F0-9]{6}", value):
        raise ValueError(f"Unsupported color {value}")
    return f"Some(rgb({int(value[1:3],16)}, {int(value[3:5],16)}, {int(value[5:7],16)}))"

def draw(node, dx=0, dy=0):
    tag = node.tag.split("}")[-1]
    if tag in ("svg", "g"):
        if transform := node.get("transform"):
            tx, ty = re.fullmatch(r"translate\(([-\d.]+) ([-\d.]+)\)", transform).groups()
            dx += float(tx)
            dy += float(ty)
        for child in node:
            yield from draw(child, dx, dy)
        return
    fill = color(node.get("fill", "#29262c"))
    stroke = color(node.get("stroke", "none"))
    width = round(float(node.get("stroke-width", "1")) * 10)
    if tag == "path":
        yield f"canvas.path(&[{geometry(node.attrib['d'], dx, dy)}], {fill}, {stroke}, {width});"
    elif tag == "ellipse":
        cx, cy, rx, ry = (float(node.attrib[key]) for key in ("cx", "cy", "rx", "ry"))
        rect = ", ".join(str(round(v*10)) for v in (cx+dx-rx, cy+dy-ry, cx+dx+rx, cy+dy+ry))
        yield f"canvas.oval([{rect}], {fill}, {stroke}, {width});"
    else:
        raise ValueError(f"Unsupported SVG element {tag}")

lines = ["// Generated by scripts/compile-pet-art.py from assets/pet-final.",
         "unsafe fn draw_final_art(canvas: &Canvas, appearance: Appearance) {",
         "    use ArtPath::*;", "    match appearance {"]
for appearance, filename in [("Cat", "tuxedo"), ("Calico", "calico"), ("Dog", "shiba"), ("Panda", "panda"), ("Husky", "husky")]:
    lines.append(f"        Appearance::{appearance} => {{")
    lines.extend(f"            {line}" for line in draw(ET.parse(assets / f"{filename}.svg").getroot()))
    lines.append("        }")
lines.extend(["    }", "}", ""])
(root / "src-tauri/src/pet_final.rs").write_text("\n".join(lines), encoding="utf-8")
